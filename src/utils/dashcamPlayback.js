// Time-based dashcam playback (Playback tab): pick a day and an hour, the
// video plays with the GPS position of the same instant on a map.
//
// One timeline, several places the video can come from. The UI never says
// which; it asks candidatesAt() for the best one at the playhead:
//
//   1. hub     — the hub-sync copy on medusa (dashcam-sync /lookup), full
//                quality. Needs the 0x1205 clip list for the file's start.
//   2. cache   — the medusa rolling cache: the newest hour per camera of
//                anything streamed (live or playback), kept by jt1078-hls.
//   3. remote  — ask the camera to play the file (0x9201) to the medusa
//                receiver. What is watched lands in the cache as it plays.
//
// Every instant here is epoch ms. Hours and days are the APP's local zone;
// the device clock zone only matters when talking to the device (BCD times)
// and is handled by utils/dashcam.js.
import { request } from '@/utils/http';
import {
  LIVE_HLS_BASE, LIVE_MEDIA_IP, LIVE_MEDIA_PORT, DASHCAM_MEDIA_BASE, MAX_CHANNELS,
  terminalSim, parseMediaList, clipUrl, body9201, body9202, body9205, customCommand,
  deviceTimeZone, MEDIA_LIST_LOOKBACK_MS,
} from '@/utils/dashcam';

export const MIN_MS = 60_000;
export const HOUR_MS = 3_600_000;
export const DAY_MS = 86_400_000;
export const KNOTS_TO_KMH = 1.852;
// A real recording file is at most an hour (V5N) — anything far longer is
// a 0x1205 decoder artefact (the multi-packet bug: years like 2001, ch 15-17).
export const MAX_CLIP_MS = 3 * HOUR_MS;
export const MOVING_KMH = 3;
export const SYNC_SLICE_BASE = DASHCAM_MEDIA_BASE.replace(/\/lookup$/, '/slice');
export const LIST_CACHE_DAYS = 7;

// --- local calendar -----------------------------------------------------------

export function dayStart(ms) {
  const d = new Date(ms);
  d.setHours(0, 0, 0, 0);
  return d.getTime();
}

export function hourStart(ms) {
  const d = new Date(ms);
  d.setMinutes(0, 0, 0);
  return d.getTime();
}

// Calendar arithmetic, so a DST day stays a day.
export function addDays(dayMs, n) {
  const d = new Date(dayMs);
  d.setDate(d.getDate() + n);
  return d.getTime();
}

// The 24 local hour starts of a day (23 or 25 on a DST day is fine: the hours
// are generated by the clock, not by adding 3600 s).
export function hoursOfDay(dayMs) {
  const out = [];
  const end = addDays(dayMs, 1);
  for (let h = 0; h < 25; h++) {
    const d = new Date(dayMs);
    d.setHours(h, 0, 0, 0);
    const t = d.getTime();
    if (t >= end) break;
    if (!out.length || t > out[out.length - 1]) out.push(t);
  }
  return out;
}

const p2 = (n) => String(n).padStart(2, '0');

export function fmtHM(ms) {
  const d = new Date(ms);
  return `${p2(d.getHours())}:${p2(d.getMinutes())}`;
}

export function fmtHMS(ms) {
  const d = new Date(ms);
  return `${p2(d.getHours())}:${p2(d.getMinutes())}:${p2(d.getSeconds())}`;
}

// 12-hour clock for the hour selector: "9 AM", "12 PM".
export function fmtHour12(ms) {
  const h = new Date(ms).getHours();
  return `${h % 12 || 12} ${h < 12 ? 'AM' : 'PM'}`;
}

// "9 – 10 AM", "11 AM – 12 PM", "11 PM – 12 AM".
export function fmtHourRange12(startMs, endMs) {
  const a = fmtHour12(startMs).split(' ');
  const b = fmtHour12(endMs).split(' ');
  return a[1] === b[1] ? `${a[0]} – ${b[0]} ${b[1]}` : `${a[0]} ${a[1]} – ${b[0]} ${b[1]}`;
}

export function fmtDay(ms, opts = { weekday: 'short', day: 'numeric', month: 'short' }) {
  return new Date(ms).toLocaleDateString(undefined, opts);
}

// --- clip list ------------------------------------------------------------------

// Drop 0x1205 decoder garbage and anything outside the cameras we drive.
export function saneClips(clips, nowMs = Date.now()) {
  return (clips || []).filter((c) => {
    if (!c || !(c.start instanceof Date) || !(c.end instanceof Date)) return false;
    const s = c.start.getTime();
    const e = c.end.getTime();
    return Number.isInteger(c.ch) && c.ch >= 1 && c.ch <= MAX_CHANNELS
      && s > Date.UTC(2020, 0, 1) && e > s && e - s <= MAX_CLIP_MS && s <= nowMs + DAY_MS;
  });
}

export function mergeClips(...lists) {
  const map = new Map();
  for (const list of lists) for (const c of list || []) map.set(c.id, c);
  return [...map.values()].sort((a, b) => a.start - b.start);
}

// Every 0x1205 answer present in a /api/positions response.
export function clipsFromPositions(positions, tz) {
  const out = [];
  for (const p of positions || []) {
    const raw = p?.attributes?.mediaList;
    if (raw != null) out.push(...parseMediaList(raw, tz));
  }
  return out;
}

// --- ranges ---------------------------------------------------------------------

export function mergeRanges(ranges) {
  const sorted = (ranges || [])
    .filter((r) => r && r.end > r.start)
    .map((r) => ({ start: r.start, end: r.end }))
    .sort((a, b) => a.start - b.start);
  const out = [];
  for (const r of sorted) {
    const last = out[out.length - 1];
    if (last && r.start <= last.end + 1000) last.end = Math.max(last.end, r.end);
    else out.push(r);
  }
  return out;
}

// Where video exists for camera `ch` in [from, to): the clip list and the
// cache together, merged and clipped. One kind of range — the UI does not
// distinguish where a piece of video lives.
export function videoRanges({ clips = [], cache = {}, ch, from, to }) {
  const raw = [
    ...clips.filter((c) => c.ch === ch).map((c) => ({ start: c.start.getTime(), end: c.end.getTime() })),
    ...(cache[ch] || []).map((r) => ({ start: r.start, end: r.end })),
  ];
  return mergeRanges(raw)
    .map((r) => ({ start: Math.max(r.start, from), end: Math.min(r.end, to) }))
    .filter((r) => r.end > r.start);
}

export function inRanges(ranges, t) {
  return (ranges || []).some((r) => t >= r.start && t < r.end);
}

// First video at or after t, else null.
export function nextVideoStart(ranges, t) {
  for (const r of ranges || []) {
    if (t < r.end) return Math.max(r.start, t);
  }
  return null;
}

// Alarm-flagged clips of camera `ch` overlapping [from, to), as instants.
export function alarmMarks(clips, ch, from, to) {
  return (clips || [])
    .filter((c) => c.ch === ch && c.alarm && c.start.getTime() < to && c.end.getTime() > from)
    .map((c) => Math.max(c.start.getTime(), from));
}

// --- GPS ------------------------------------------------------------------------

// Traccar positions -> [{ t, lat, lng, kmh, course, moving }] sorted by fix
// time. The 0x1205 answer is stored as a position that repeats the last fix,
// so duplicates by fix time are dropped.
export function toTrack(positions) {
  const seen = new Set();
  const out = [];
  for (const p of positions || []) {
    const t = new Date(p?.fixTime || p?.deviceTime || 0).getTime();
    const lat = Number(p?.latitude);
    const lng = Number(p?.longitude);
    if (!Number.isFinite(t) || !Number.isFinite(lat) || !Number.isFinite(lng)) continue;
    if (lat === 0 && lng === 0) continue;
    if (seen.has(t)) continue;
    seen.add(t);
    const kmh = (Number(p?.speed) || 0) * KNOTS_TO_KMH;
    out.push({
      t, lat, lng, kmh,
      course: Number(p?.course) || 0,
      moving: p?.attributes?.motion === true || kmh >= MOVING_KMH,
    });
  }
  return out.sort((a, b) => a.t - b.t);
}

function lerpAngle(a, b, f) {
  const d = ((((b - a) % 360) + 540) % 360) - 180;
  return (a + d * f + 360) % 360;
}

// Interpolated fix at instant t (null outside the track or across a gap
// longer than maxGapMs — the vehicle was off, do not invent a path).
export function fixAt(track, t, maxGapMs = 10 * MIN_MS) {
  if (!track?.length) return null;
  if (t < track[0].t || t > track[track.length - 1].t) return null;
  let lo = 0;
  let hi = track.length - 1;
  while (hi - lo > 1) {
    const mid = (lo + hi) >> 1;
    if (track[mid].t <= t) lo = mid;
    else hi = mid;
  }
  const a = track[lo];
  const b = track[hi];
  if (b.t - a.t > maxGapMs) return t - a.t <= maxGapMs ? { ...a, t } : null;
  const f = b.t === a.t ? 0 : (t - a.t) / (b.t - a.t);
  return {
    t,
    lat: a.lat + (b.lat - a.lat) * f,
    lng: a.lng + (b.lng - a.lng) * f,
    kmh: a.kmh + (b.kmh - a.kmh) * f,
    course: lerpAngle(a.course, b.course, f),
  };
}

// TrackMap's format: [[seconds since `from`, lat, lng, kmh, course], ...] at
// 1 Hz (its progress line indexes by whole seconds), only where there is a fix.
export function trackPoints(track, from, to) {
  const inWin = (track || []).filter((p) => p.t >= from - MIN_MS && p.t <= to + MIN_MS);
  if (inWin.length < 2) return [];
  const a = Math.max(from, inWin[0].t);
  const b = Math.min(to, inWin[inWin.length - 1].t);
  const out = [];
  for (let t = Math.ceil((a - from) / 1000) * 1000 + from; t <= b; t += 1000) {
    const f = fixAt(inWin, t);
    if (f) out.push([(t - from) / 1000, f.lat, f.lng, f.kmh, f.course]);
  }
  return out;
}

// Minutes spent moving in each local hour of the day: [{ hour, minutes }].
export function drivingByHour(track, dayMs) {
  const hours = hoursOfDay(dayMs);
  const minutes = hours.map(() => new Set());
  for (const p of track || []) {
    if (!p.moving) continue;
    for (let i = hours.length - 1; i >= 0; i--) {
      if (p.t >= hours[i]) {
        if (i === hours.length - 1 && p.t >= addDays(dayMs, 1)) break;
        minutes[i].add(Math.floor((p.t - hours[i]) / MIN_MS));
        break;
      }
    }
  }
  return hours.map((h, i) => ({ hour: h, minutes: Math.min(60, minutes[i].size) }));
}

// Speed samples in [from, to) for the timeline sparkline: [{ t, kmh }].
export function speedSamples(track, from, to) {
  return (track || []).filter((p) => p.t >= from && p.t < to).map((p) => ({ t: p.t, kmh: p.kmh }));
}

// --- sources ----------------------------------------------------------------------

// Candidate sources for camera `ch` at instant t, best first. hub/remote come
// from the clip list; cache from the medusa index. The caller verifies hub
// with a HEAD (hubChecks) and needs the camera online for remote.
export function candidatesAt({ t, ch, clips = [], cache = {}, uniqueId }) {
  const out = [];
  const clip = clips.find((c) => c.ch === ch && t >= c.start.getTime() && t < c.end.getTime());
  if (clip) out.push({ kind: 'hub', url: clipUrl(uniqueId, clip), base: clip.start.getTime(), end: clip.end.getTime(), clip });
  const r = (cache[ch] || []).find((x) => t >= x.start && t < x.end);
  if (r) out.push({ kind: 'cache', url: r.url, base: r.start, end: r.end, active: !!r.active });
  if (clip) out.push({ kind: 'remote', base: t, end: clip.end.getTime(), clip });
  return out;
}

// Where [from, to] of camera `ch` can be downloaded from, best first:
// a hub slice (needs the HEAD to have passed) or a cache slice. Both are mp4
// attachments cut server-side; neither pulls a whole hour.
export function downloadCandidates({ ch, from, to, clips = [], cache = {}, uniqueId, sim }) {
  const out = [];
  const clip = clips.find((c) => c.ch === ch && from >= c.start.getTime() && from < c.end.getTime());
  if (clip) {
    const s = clip.start.getTime();
    const end = Math.min(to, clip.end.getTime());
    const lookup = clipUrl(uniqueId, clip);
    const path = lookup.slice(DASHCAM_MEDIA_BASE.length);
    out.push({
      kind: 'hub', check: lookup, from, to: end,
      url: `${SYNC_SLICE_BASE}${path.replace(/\.mp4$/, '')}?from=${((from - s) / 1000).toFixed(1)}&to=${((end - s) / 1000).toFixed(1)}`,
    });
  }
  const r = (cache[ch] || []).find((x) => from >= x.start && from < x.end);
  if (r) {
    const end = Math.min(to, r.end);
    out.push({ kind: 'cache', from, to: end, url: `${LIVE_HLS_BASE}/_clip?sim=${sim}&ch=${ch}&from=${Math.round(from)}&to=${Math.round(end)}` });
  }
  return out;
}

// [from, to] of `minutes` centred on t, kept inside [lo, hi].
export function sliceAround(t, minutes, lo, hi) {
  const len = Math.min(minutes * MIN_MS, hi - lo);
  let from = t - len / 2;
  from = Math.max(lo, Math.min(from, hi - len));
  return { from: Math.round(from), to: Math.round(from + len) };
}

// Download range: the `minutes` that END at the playhead (2:30 + 3 min -> 2:27-2:30).
export const DOWNLOAD_MINUTES = [1, 3, 5, 10];
export function sliceBefore(t, minutes) {
  const to = Math.floor(t / 1000) * 1000;
  return { from: to - minutes * MIN_MS, to };
}

// `base` minus `minus`, both [{ start, end }].
export function subtractRanges(base, minus) {
  let out = mergeRanges(base);
  for (const m of mergeRanges(minus)) {
    const next = [];
    for (const r of out) {
      if (m.end <= r.start || m.start >= r.end) { next.push(r); continue; }
      if (m.start > r.start) next.push({ start: r.start, end: m.start });
      if (m.end < r.end) next.push({ start: m.end, end: r.end });
    }
    out = next;
  }
  return out;
}

// How to deliver camera `ch` over [from, to] as one mp4:
//   { kind: 'none' }                          no video anywhere in the range
//   { kind: 'hub', url, from, to }            one hub-synced file holds it all
//   { kind: 'cache', url, from, to, pieces }  cut from the rolling cache after
//                                             streaming `pieces` from the camera
// The range is trimmed to where video exists. `pieces` are only the parts the
// cache lacks, each inside ONE recording file (the camera plays a request
// within a file), so nothing already on the server is pulled again.
// `hubOk(lookupUrl)` says whether the hub copy of that file exists.
export function planDownload({ ch, from, to, clips = [], cache = {}, uniqueId, sim, hubOk = () => false }) {
  const vids = videoRanges({ clips, cache, ch, from, to });
  if (!vids.length) return { kind: 'none' };
  const a = vids[0].start;
  const b = vids[vids.length - 1].end;

  const whole = clips.find((c) => c.ch === ch && c.start.getTime() <= a && c.end.getTime() >= b);
  if (whole && hubOk(clipUrl(uniqueId, whole))) {
    const hub = downloadCandidates({ ch, from: a, to: b, clips: [whole], cache: {}, uniqueId, sim })[0];
    return { kind: 'hub', url: hub.url, from: a, to: b };
  }

  const missing = subtractRanges([{ start: a, end: b }], cache[ch] || []);
  const pieces = [];
  for (const g of missing) {
    for (const c of clips) {
      if (c.ch !== ch) continue;
      const s = Math.max(g.start, c.start.getTime());
      const e = Math.min(g.end, c.end.getTime());
      if (e - s >= 1000) pieces.push({ start: s, end: e });
    }
  }
  pieces.sort((x, y) => x.start - y.start);
  return {
    kind: 'cache', from: a, to: b, pieces,
    url: `${LIVE_HLS_BASE}/_clip?sim=${sim}&ch=${ch}&from=${Math.round(a)}&to=${Math.round(b)}`,
  };
}

// Milliseconds of [start, end] already in the cache ranges `rs`.
export function coveredMs(rs, start, end) {
  return mergeRanges(rs || []).reduce((sum, r) => sum + Math.max(0, Math.min(r.end, end) - Math.max(r.start, start)), 0);
}

// --- device + medusa I/O ----------------------------------------------------------------

export function recIndexUrl(device) {
  return `${LIVE_HLS_BASE}/_rec?sim=${terminalSim(device)}`;
}

// medusa /_rec -> { [ch]: [{ start, end, url, active }] }
export function parseRecIndex(json) {
  const out = {};
  for (const [ch, list] of Object.entries(json?.channels || {})) {
    out[Number(ch)] = (list || [])
      .filter((r) => r.end_ms > r.start_ms)
      .map((r) => ({ start: r.start_ms, end: r.end_ms, url: `${LIVE_HLS_BASE}/${r.playlist}`, active: !!r.active }));
  }
  return out;
}

export async function fetchRecIndex(device) {
  const json = await request.send({ url: recIndexUrl(device), simple: true });
  return parseRecIndex(typeof json === 'string' ? JSON.parse(json) : json);
}

// Tell the medusa receiver which device instant the next stream on (sim, ch)
// starts at, so the cache files it under the right time. Sent right before 9201.
export function labelPlayback(device, ch, startMs) {
  const q = `sim=${terminalSim(device)}&ch=${Number(ch)}&start=${Math.round(startMs)}`;
  return request.send({ url: `${LIVE_HLS_BASE}/_session?${q}`, method: 'POST', simple: true });
}

// 0x9201 to the medusa receiver (NOT Traccar's): the same path as live, so the
// rolling cache records it.
export function playbackCommand(device, ch, start, end) {
  return customCommand('9201', body9201({
    ip: LIVE_MEDIA_IP, tcpPort: LIVE_MEDIA_PORT, ch: Number(ch),
    start: new Date(start), end: new Date(end), tz: deviceTimeZone(device),
  }));
}

export function stopPlaybackCommand(ch) {
  return customCommand('9202', body9202(Number(ch), 2));
}

// 0x9205 for camera `ch` over [from, to). Always ONE camera per request: the
// V5N records 5-minute files, so an hour of 3 cameras is 36 entries, which the
// device sub-packages (attr bit 13, >~33 entries) — and Traccar decodes each
// sub-packet as its own list (packet 2 reads as count 131366, channel 16/17,
// year 2001). One camera-hour is 12-13 entries, a single packet.
export function listCommand(device, from, to, ch) {
  return customCommand('9205', body9205(Number(ch), new Date(from), new Date(to), deviceTimeZone(device)));
}

// 0x1205 answers in a positions response: [{ id, receivedMs, raw, count }].
export function listEntries(positions) {
  const out = [];
  for (const p of positions || []) {
    const raw = p?.attributes?.mediaList;
    if (raw == null) continue;
    out.push({
      id: p.id,
      receivedMs: new Date(p.serverTime || p.deviceTime || p.fixTime).getTime(),
      raw,
      count: p.attributes.mediaCount,
    });
  }
  return out.sort((a, b) => a.receivedMs - b.receivedMs);
}

function rawLength(raw) {
  if (Array.isArray(raw)) return raw.length;
  try {
    const v = JSON.parse(raw);
    return Array.isArray(v) ? v.length : 0;
  } catch {
    return 0;
  }
}

// The answer to a per-camera 0x9205 sent at `sinceMs`: the first list received
// since then whose entries are ALL for camera `ch` (an empty list counts — the
// camera has nothing there). Anything else is another request's answer, the
// one-file echo of a 0x9201, or a mis-decoded sub-packet, and is skipped.
// `clean` is false when entries were dropped or the declared count disagrees —
// then the window must not be marked as checked.
// `echoes` holds echoKey()s of 0x9201 requests the app sent: the camera
// echoes each as a one-entry 0x1205 that must not pass for a full answer.
// One registry for the whole app — the player AND the download sheet send
// 0x9201, and either's echo can land while the other is waiting for a list.
export const playbackEchoes = new Set();

export function echoKey(ch, startMs, endMs) {
  const s = (ms) => Math.floor(ms / 1000) * 1000;   // BCD times have whole seconds
  return `${Number(ch)}|${s(startMs)}|${s(endMs)}`;
}

export function pickListAnswer(entries, sinceMs, ch, tz, used = new Set(), echoes = new Set()) {
  for (const e of entries || []) {
    if (used.has(e.id) || !(e.receivedMs >= sinceMs)) continue;
    const parsed = parseMediaList(e.raw, tz);
    if (parsed.some((c) => c.ch !== Number(ch))) continue;
    if (parsed.length === 1 && echoes.has(echoKey(parsed[0].ch, parsed[0].start.getTime(), parsed[0].end.getTime()))) continue;
    const n = rawLength(e.raw);
    const sane = saneClips(parsed);
    return {
      id: e.id,
      clips: sane,
      clean: sane.length === n && (e.count == null || Number(e.count) === n),
    };
  }
  return null;
}

export function fetchPositions(server, deviceId, from, to) {
  return request.send({
    url: `https://${server}/api/positions`,
    params: { deviceId: Number(deviceId), from: new Date(from).toISOString(), to: new Date(to).toISOString() },
    isTraccar: true,
  });
}

// 0x1205 answers received since `sinceMs`. /api/positions filters on fixTime,
// and the answer carries the device's LAST fix time (minutes old when parked),
// so look back generously and let pickListAnswer judge by serverTime.
export async function fetchListEntries(server, deviceId, sinceMs) {
  const pos = await fetchPositions(server, deviceId, sinceMs - MEDIA_LIST_LOOKBACK_MS, Date.now() + MIN_MS);
  return listEntries(pos);
}

// Traccar daily summary: [{ day, km }] for the week strip.
export async function fetchDailyKm(server, deviceId, from, to) {
  const rows = await request.send({
    url: `https://${server}/api/reports/summary`,
    params: { deviceId: Number(deviceId), from: new Date(from).toISOString(), to: new Date(to).toISOString(), daily: true },
    isTraccar: true,
  });
  return (Array.isArray(rows) ? rows : []).map((r) => ({
    day: dayStart(new Date(r.startTime || r.startDate || 0).getTime()),
    km: (Number(r.distance) || 0) / 1000,
  }));
}

// --- clip-list cache (per viewer, per device) ----------------------------------------
//
// The app asks for one hour at a time, and Traccar files each 0x1205 answer
// under the day it ARRIVED, not the day it covers. Remember answers and the
// windows they covered locally so a revisited hour does not wake the camera.

// v2: v1 marked hours "checked" from mis-decoded all-camera answers that held
// no usable entries; those windows must be asked again.
const listKey = (deviceId) => `dashcam:lists:v2:${deviceId}`;

export function loadListCache(deviceId, tz, nowMs = Date.now()) {
  try {
    const raw = JSON.parse(localStorage.getItem(listKey(deviceId)) || 'null');
    if (!raw) return { checked: [], clips: [] };
    const cutoff = nowMs - LIST_CACHE_DAYS * DAY_MS;
    return {
      checked: (raw.checked || []).filter((w) => w[1] > cutoff),
      clips: saneClips(parseMediaList(raw.items || [], tz), nowMs).filter((c) => c.end.getTime() > cutoff),
    };
  } catch {
    return { checked: [], clips: [] };
  }
}

export function saveListCache(deviceId, { checked, clips }, nowMs = Date.now()) {
  try {
    const cutoff = nowMs - LIST_CACHE_DAYS * DAY_MS;
    const items = (clips || [])
      .filter((c) => c.end.getTime() > cutoff)
      .map((c) => ({ ch: c.ch, start: c.startRaw, end: c.endRaw, alarm: c.alarm, size: c.size }));
    localStorage.setItem(listKey(deviceId), JSON.stringify({
      checked: (checked || []).filter((w) => w[1] > cutoff).slice(-200),
      items,
    }));
  } catch { /* private mode / quota: the cache is a convenience */ }
}

// Was [from, to) covered by a 0x9205 answer?
export function isChecked(checked, from, to) {
  return (checked || []).some((w) => w[0] <= from && w[1] >= to);
}
